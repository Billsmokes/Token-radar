const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted array, or null when it is empty. */
function medianOf(sorted: number[]): number | null {
  if (sorted.length === 0) return null;
  const mid = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 1) return sorted[mid]!;
  return (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/**
 * The base multiple, calibrated from the snapshot itself: the median market-cap-to-TVL ratio of its
 * live-token protocols. The market's own price per dollar of TVL, not a chosen constant. Falls back
 * to the house 0.25 when the snapshot holds too few live comparables to trust a median.
 */
export function calibrateBaseMultiple(snapshot: Snapshot): Calibration {
  const ratios = snapshot.protocols
    .filter((p) => !isPreToken(p) && p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0)
    .map((p) => (p.mcap_usd as number) / p.tvl_usd)
    .sort((a, b) => a - b);
  if (ratios.length < CALIBRATION_MIN) {
    return { comparables: ratios.length, median: BASE_FALLBACK, p25: BASE_FALLBACK, p75: BASE_FALLBACK, source: 'fallback' };
  }
  const median = medianOf(ratios) ?? BASE_FALLBACK;
  const p25 = ratios[Math.floor(ratios.length * 0.25)] ?? median;
  const p75 = ratios[Math.floor(ratios.length * 0.75)] ?? median;
  return { comparables: ratios.length, median, p25, p75, source: 'live-median' };
}

/** The model's constants with the calibrated base multiple resolved. */
export function resolveModel(snapshot: Snapshot): { model: ModelConstants; calibration: Calibration } {
  const calibration = calibrateBaseMultiple(snapshot);
  const model: ModelConstants = {
    base_multiple: calibration.median,
    base_source: calibration.source,
    growth_weight: 0.5,
    growth_floor: -60,
    growth_cap: 120,
    maturity_floor: 0.6,
    maturity_range: 0.4,
    maturity_days: 1095,
    unknown_age_days: 365,
    breadth_step: 0.03,
    breadth_cap_chains: 4,
  };
  return { model, calibration };
}

/** The four multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(protocol: SnapshotProtocol, asOf: string, model: ModelConstants): { implied: number; growthPct: number; growthMult: number; maturityMult: number; breadthMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const extraChains = Math.min(Math.max(protocol.chains.length - 1, 0), model.breadth_cap_chains);
  const breadthMult = 1 + extraChains * model.breadth_step;
  const base = protocol.tvl_usd * model.base_multiple;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult * breadthMult));
  return { implied, growthPct, growthMult, maturityMult, breadthMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** A name that says the product itself is a wrapped or staked derivative of something that trades. */
const WRAPPED = /\b(wrapped|staked|staking)\b/i;

/** A name that begins with a centralised exchange's name: an exchange product, not a launch. */
const EXCHANGE_NAMES = ['Binance', 'Coinbase', 'Bybit', 'Kraken', 'Bitget', 'OKX', 'Bitfinex', 'Gemini'];

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank: pre-token, not an exchange, not a versioned pool, and
 * not a wrapped or staked product of one that trades. This is the brief's own definition of a launch
 * candidate, applied to the early radar below the watchlist floor. The watchlist itself is sealed and
 * governs the above-floor set; the early rule does not re-impose the watchlist's category screen,
 * because bridges and liquid-staking protocols do launch genuine governance tokens — only products
 * whose own name says they are a wrapped or staked derivative are removed.
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category === 'CEX') return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED.test(p.name)) return false;
  if (EXCHANGE_NAMES.some((e) => p.name.startsWith(e))) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
