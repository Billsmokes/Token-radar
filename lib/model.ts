// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// pre-token protocol below the watchlist floor that meets the brief's own definition of a launch
// candidate: it records no token, and it is not a wrapped or staked product of one that trades, not an
// exchange, and not a versioned pool of another protocol. The early radar is complete, not a top-N cut:
// every protocol that meets the definition is ranked. A protocol is pre-token when its index entry
// records no token (no market cap, no CoinGecko id, no symbol); the snapshot's live-token protocols
// are kept apart and shown as the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base       = median(mcap_usd / tvl_usd) over the snapshot's live-token protocols
//                (the market's own FDV/TVL; 0.25 when fewer than 10 comparables exist)
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + min(chains - 1, 4) x 0.03   (a protocol live on more chains reaches more users)
//   implied    = max(1, round(tvl_usd x base x growthMult x maturity x breadth))
//
// The base multiple is calibrated, not chosen: it is the median of what the market already pays per
// dollar of TVL for protocols that do trade, computed from this same sealed snapshot at run time, so
// the number is a fact about the snapshot, not a house guess. No protocol name is ever special-cased:
// the same function scores every row.

